# Generates docs/EXAMPLES.md: real output of profinetctl commands against
# rt-labs p-net (profinet-interop's image) and two go-profinet IO-Devices
# (go-profinet's interop tool otfnode) on a Docker bridge network. Needs
# Docker, the profinet-interop images and ../go-profinet.
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
GP=${GO_PROFINET_DIR:-$ROOT/../go-profinet}
WORK=$(mktemp -d)
NET=profinetctl-examples
SUBNET=${EXAMPLES_SUBNET:-10.143.5}
PNET_IMAGE=${PROFINET_INTEROP_PNET_IMAGE:-profinet-interop-pnet:dev}
IMAGE=${EXAMPLES_TOOL_IMAGE:-debian:bookworm-slim}
# go-profinet's interop runner image has iproute2, which otfnode needs to
# apply a DCP Set IP to its interface.
OTF_IMAGE=go-profinet-interop-runner:dev
ARCH=$(docker version --format '{{.Server.Arch}}')
OUT="$ROOT/docs/EXAMPLES.md"

cleanup() {
	docker rm -f "$NET-pnet" "$NET-otf-a" "$NET-otf-b" >/dev/null 2>&1 || true
	docker network rm "$NET" >/dev/null 2>&1 || true
	rm -rf "$WORK"
}
trap cleanup EXIT

(cd "$ROOT" && GOWORK=off CGO_ENABLED=0 GOOS=linux GOARCH="$ARCH" go build -o "$WORK/profinetctl" .)
(cd "$GP" && GOWORK=off CGO_ENABLED=0 GOOS=linux GOARCH="$ARCH" go build -o "$WORK/otfnode" ./interop/otfnode)
cp "$ROOT/testdata/pnet-model.json" "$WORK/"
docker build -q -t "$OTF_IMAGE" "$GP/interop/runner" >/dev/null

docker network create --subnet "$SUBNET.0/24" "$NET" >/dev/null
# LLDP (01:80:C2:00:00:0E) crosses a Linux bridge only with bit 14 of its
# group_fwd_mask set.
br="br-$(docker network inspect -f '{{.Id}}' "$NET" | cut -c1-12)"
docker run --rm --privileged --network host "$IMAGE" sh -c "echo 16384 > /sys/class/net/$br/bridge/group_fwd_mask" || true
run_dev() { # name host args...
	n=$1
	h=$2
	shift 2
	docker run -d --name "$NET-$n" --network "$NET" --ip "$SUBNET.$h" --cap-add NET_RAW --cap-add NET_ADMIN -v "$WORK":/w "$@" >/dev/null
}
run_dev pnet 10 "$PNET_IMAGE" device --station pnet-dut
run_dev otf-a 20 "$OTF_IMAGE" /w/otfnode device -i eth0 -station otf-a -gsdml-out /w/otf-device.xml -alarm-after 2s
run_dev otf-b 21 "$OTF_IMAGE" /w/otfnode device -i eth0 -station otf-b
sleep 8

# ex [--note TEXT] ARGS...: run profinetctl and append the command and its
# output to the document.
ex() {
	{
		printf '```console\n$ profinetctl'
		for a in "$@"; do
			case "$a" in
			*" "*) printf " '%s'" "$a" ;;
			*) printf ' %s' "$a" ;;
			esac
		done
		printf '\n'
		set +e
		docker run --rm --network "$NET" --ip "$SUBNET.3" --mac-address 02:42:0a:8f:05:03 --cap-add NET_RAW --cap-add NET_ADMIN \
			-e PROFINETCTL_INTERFACE=eth0 -v "$WORK":/w -w /w "$IMAGE" /w/profinetctl "$@" 2>&1
		code=$?
		set -e
		[ "$code" -eq 0 ] || printf '[exit code %d]\n' "$code"
		printf '```\n\n'
	} >>"$OUT.tmp"
}
section() { printf '## %s\n\n%s\n\n' "$1" "$2" >>"$OUT.tmp"; }

cat >"$OUT.tmp" <<HEAD
<!-- Generated by scripts/examples.sh (make examples-doc); do not edit. -->

# profinetctl by example

Real output, generated on $(date -u +%Y-%m-%d) by \`make examples-doc\`: profinetctl in a Linux container
on a Docker bridge network with three IO-Devices: **pnet-dut**, rt-labs
p-net's sample application (an independent implementation), and **otf-a**
and **otf-b**, go-profinet IO-Devices. The interface is set with
\`PROFINETCTL_INTERFACE=eth0\`. MAC addresses, UUIDs and timings differ
from run to run.

HEAD

section "Interfaces and discovery" "Every command takes \`--format text\` (default), \`table\` or \`json\`."
ex interfaces
ex discover --wait 2s
ex discover --wait 2s -o table
ex discover --wait 1s --station otf-b -o json
ex identify -s pnet-dut

section "Names, addresses, signal" "A Set is temporary unless \`--permanent\` is given."
ex name get -s pnet-dut
ex name set pnet-renamed -s pnet-dut
ex name set pnet-dut -s pnet-renamed
ex ip get -s otf-b
ex ip set "$SUBNET.22/24" -s otf-b
ex ip get -s otf-b
ex ip set "$SUBNET.21/24" -s otf-b
ex signal -s pnet-dut

section "Identification, records and diagnosis" "Reads use ReadImplicit: no AR is needed."
ex device info -s pnet-dut
ex im read -s pnet-dut
ex im read -s otf-a -o table
ex record read -s pnet-dut --index 0xF000
ex record read -s otf-a --slot 2 --index 0x10
ex diagnostics -s pnet-dut
ex status -s otf-a

section "Writes" "go-profinet devices accept a device access AR (IOSAR) for writes; p-net does not, and profinetctl then writes in an IO-Controller AR when it is given the expected configuration (\`--model\` or \`--gsdml\`)."
ex record write -s otf-a --slot 2 --index 0x10 --data 0005
ex record read -s otf-a --slot 2 --index 0x10
ex record write -s pnet-dut --slot 1 --index 123 --data 01020304
ex record write -s pnet-dut --slot 1 --index 123 --data 01020304 --model pnet-model.json
ex im write -s pnet-dut --location 'bench 2' --model pnet-model.json
ex im read -s pnet-dut --record 1

section "LLDP and topology" ""
ex lldp neighbors --wait 6s
ex topology --wait 2s

section "GSDML" "otf-device.xml is the GSDML file otf-a writes for itself."
ex gsdml inspect otf-device.xml
ex gsdml validate otf-device.xml
ex gsdml modules otf-device.xml
ex gsdml submodules otf-device.xml --module 0x20

section "Application relationships and cyclic data" "profinetctl acts as IO-Controller with the expected configuration of the device."
ex ar -s pnet-dut --model pnet-model.json --reduction-ratio 8
ex iocr -s pnet-dut --model pnet-model.json
ex io status -s pnet-dut --model pnet-model.json --output 2:1:1122334455667788 --settle 1s
ex io monitor -s otf-a --gsdml otf-device.xml --plug 3=0x30 --interval 500ms --duration 2s
ex io statistics -s pnet-dut --model pnet-model.json --duration 3s
ex connect -s otf-a --gsdml otf-device.xml --plug 3=0x30 --output 2:1:a1b2c3d4 --duration 4s
ex connect -s pnet-dut --model pnet-model.json --duration 1s -o json

section "Errors and exit codes" "Exit codes are stable (see exitcodes.md); with \`-o json\` the error is a JSON object on stdout."
ex identify -s nobody --wait 500ms
ex identify -s nobody --wait 500ms -o json
ex reset -s otf-b
ex reset -s otf-b --confirm otf-a
ex reset -s otf-b --mode communication --confirm otf-b
ex version

mv "$OUT.tmp" "$OUT"
echo "wrote $OUT"
